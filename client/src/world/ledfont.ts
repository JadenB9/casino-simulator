/** Digits keep their full five columns so amounts line up; everything else is trimmed to its ink. */
const FIXED = new Set('0123456789');
const SPACE_WIDTH = 3;

interface Glyph {
  width: number;
  /** Rows as bit masks over `width` columns, high bit on the left. */
  rows: readonly number[];
}

const cache = new Map<string, Glyph | null>();

function glyph(ch: string): Glyph | null {
  let g = cache.get(ch);
  if (g !== undefined) return g;
  const rows = GLYPHS[ch];
  if (!rows) {
    g = null;
  } else if (FIXED.has(ch)) {
    g = { width: 5, rows };
  } else {
    // trim empty columns on both sides
    const ink = rows.reduce((a, r) => a | r, 0);
    let left = 4;
    let right = 0;
    for (let c = 0; c < 5; c++) {
      if (ink & (1 << (4 - c))) {
        left = Math.min(left, c);
        right = Math.max(right, c);
      }
    }
    const width = right - left + 1;
    g = { width, rows: rows.map((r) => (r >> (4 - right)) & ((1 << width) - 1)) };
  }
  cache.set(ch, g);
  return g;
}

/** The sign's characters: upper case, and anything it has no glyph for becomes a space. */
export function ledText(s: string): string {
  return Array.from(s.toUpperCase())
    .map((ch) => (ch === ' ' || glyph(ch) ? ch : ' '))
    .join('');
}

/** Columns a piece of text takes, spacing between letters included (none after the last). */
export function textWidth(s: string): number {
  let w = 0;
  let n = 0;
  for (const ch of ledText(s)) {
    w += ch === ' ' ? SPACE_WIDTH : glyph(ch)!.width;
    n++;
  }
  return n ? w + (n - 1) * GAP : 0;
}

/** A piece of text in one colour (linear RGB, 0-1 each; the sign's shader brightens it). */
export interface Run {
  text: string;
  color: readonly [number, number, number];
}

/** An RGBA image, one pixel per LED, rows top to bottom. */
export interface Tape {
  width: number;
  height: number;
  data: Uint8ClampedArray;
}

/**
 * Lay runs out left to right after `lead` blank columns, then `tail` more. Letters inside a run are
 * GAP apart; runs follow each other with a GAP too (put spaces in the text for more).
 */
export function layoutTape(runs: readonly Run[], opts: { lead?: number; tail?: number; minWidth?: number; maxWidth?: number } = {}): Tape {
  const lead = opts.lead ?? 0;
  const body = runs.reduce((w, r, i) => w + textWidth(r.text) + (i > 0 && r.text ? GAP : 0), 0);
  const width = Math.max(1, Math.min(opts.maxWidth ?? 4096, Math.max(opts.minWidth ?? 0, lead + body + (opts.tail ?? 0))));
  const data = new Uint8ClampedArray(width * TAPE_ROWS * 4);
  // unlit LEDs are black and opaque; the shader draws the dark lens itself
  for (let i = 3; i < data.length; i += 4) data[i] = 255;
  let x = lead;
  runs.forEach((run, i) => {
    if (i > 0 && run.text) x += GAP;
    const [r, g, b] = run.color.map((c) => Math.round(Math.min(1, Math.max(0, c)) * 255));
    let first = true;
    for (const ch of ledText(run.text)) {
      if (!first) x += GAP;
      first = false;
      if (ch === ' ') {
        x += SPACE_WIDTH;
        continue;
      }
      const gl = glyph(ch)!;
      for (let row = 0; row < 7; row++) {
        const bits = gl.rows[row]!;
        for (let c = 0; c < gl.width; c++) {
          if (!(bits & (1 << (gl.width - 1 - c)))) continue;
          const px = x + c;
          if (px < 0 || px >= width) continue;
          const o = ((row + 1) * width + px) * 4;
          data[o] = r!;
          data[o + 1] = g!;
          data[o + 2] = b!;
        }
      }
      x += gl.width;
    }
  });
  return { width, height: TAPE_ROWS, data };
}

/** Where text of this width starts to sit centred on a sign `cols` wide. */
export function centred(width: number, cols: number): number {
  return Math.max(0, Math.floor((cols - width) / 2));
}
